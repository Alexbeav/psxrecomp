/*
 * Source-profile reverb against the stock oracle (PS1B-109).
 *
 * Fixture R1: the last four reverb steps of frame 122985 of the Vampire
 * Hunter D TAS on the stock core (BizHawk 2.7, Eagle oracle). The stock
 * observer dumped the work area, the reverb registers and the 64 ticks of
 * reverb input held at that frame; scripts/rvb_fixture.py of the PS1B-109
 * lane turned them into the tables below: every work-area word the four
 * steps read, and the 32 words they store. Voice 5 of that title runs past
 * its sample into the work area (mBASE 79020h) and decodes these stores as
 * ADPCM headers, so a store that differs from the oracle changes when the
 * voice ends (ENVX 0 at return 122984 on the oracle, 7FF7h on the native).
 *
 * The test feeds the 64 inputs through the CD input (volume -8000h, CD
 * reverb on) with every voice silent, stores disabled for the first 56
 * ticks and enabled for the last 8, which hold the four steps.
 *
 * Build/run: ctest -R spu_source_reverb_test
 */

