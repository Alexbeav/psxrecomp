#define NREAD  (sizeof(fx_read_addr) / sizeof(fx_read_addr[0]))
#define NWRITE (sizeof(fx_write_addr) / sizeof(fx_write_addr[0]))

static void put16(uint32_t a, uint16_t v) {
    spu_ram[a] = (uint8_t)(v & 0xFFu);
    spu_ram[a + 1u] = (uint8_t)(v >> 8);
}

int main(void) {
    spu_init();
    source_key_timing = 1;
    for (int i = 0; i < SPU_VOICE_COUNT; i++) voices[i].adsr_phase = ADSR_RELEASE;
    for (unsigned i = 0; i < 32; i++)
        spu_regs[reg_index(0x1F801DC0u + 2u * i)] = fx_regs[i];
    spu_regs[reg_index(0x1F801DA2u)] = FX_MBASE;
    spu_regs[reg_index(0x1F801DB0u)] = 0x8000u;  /* CD volume -8000h: in = -cd */
    spu_regs[reg_index(0x1F801DB2u)] = 0x8000u;
    rev_cur = FX_CUR_BYTES;

    for (unsigned i = 0; i < NWRITE; i++) put16(fx_write_addr[i], 0xDEADu);
    for (unsigned i = 0; i < NREAD; i++) put16(fx_read_addr[i], fx_read_val[i]);

    int16_t cd[64 * 2];
    for (unsigned n = 0; n < 64; n++) {
        cd[n * 2 + 0] = (int16_t)-fx_in_l[n];
        cd[n * 2 + 1] = (int16_t)-fx_in_r[n];
    }
    spu_cd_audio_push(cd, 64);

    for (unsigned n = 0; n < 64; n++) {
        /* Enable, unmute, CD on, CD reverb on; stores only for the last 8. */
        spu_regs[reg_index(0x1F801DAAu)] = (uint16_t)(0xC005u | (n >= 56 ? 0x0080u : 0u));
        int16_t out[2];
        fixture_cycle += 768u;
        spu_catch_up();
        if (spu_output_pop(out, 1) != 1) return 2;
    }

    int bad = 0;
    for (unsigned i = 0; i < NWRITE; i++) {
        uint32_t a = fx_write_addr[i];
        uint16_t got = (uint16_t)(spu_ram[a] | (spu_ram[a + 1u] << 8));
        if (got != fx_write_val[i]) {
            fprintf(stderr, "FAIL: store %u at %05X: got %04X, oracle %04X\n",
                    i, (unsigned)a, got, fx_write_val[i]);
            bad++;
        }
    }
    printf("%s: R1 work-area stores matching the oracle = %u/%u\n",
           bad ? "FAIL" : "PASS", (unsigned)(NWRITE - bad), (unsigned)NWRITE);
    /* Boot17/18 separates CD input into SCD2 and carries a guest sample
     * phase. The new wire round-trips exactly; old SPK2 native sections are
     * rejected even under the old container-compatibility environment flag.
     * Historical e841 migration evidence does not qualify this new format. */
    const uint32_t n = spu_snapshot_bytes();
    uint8_t *wire = malloc(n), *again = malloc(n), *short_wire = malloc(n);
    if (!wire || !again || !short_wire) return 2;
    spu_snapshot_write(wire);
    if (!spu_snapshot_validate(wire, n) || !spu_snapshot_read(wire, n)) bad++;
    spu_snapshot_write(again);
    if (memcmp(wire, again, n)) bad++;
    const uint32_t source = n - SPU_SNAPSHOT_CLOCK_BYTES - SOURCE_SPU_TAIL_BYTES;
    const uint32_t reverb = source + SOURCE_SPU_TAIL_BYTES - 385u;
    memcpy(short_wire, wire, reverb);
    memcpy(short_wire + reverb, wire + reverb + 385u, n - reverb - 385u);
    short_wire[source + 3u] = 0x32u;
    putenv("PSX_TAS_RESUME_COMPATIBLE_BUILD=0");
    if (spu_snapshot_validate(short_wire, n - 385u)) bad++;
    putenv("PSX_TAS_RESUME_COMPATIBLE_BUILD=1");
    if (spu_snapshot_validate(short_wire, n - 385u)) bad++;
    wire[source + 36u + 64u] = 32u;
    if (spu_snapshot_validate(wire, n)) bad++;
    wire[source + 36u + 64u] = 0u;
    if (spu_snapshot_validate(wire, n - 1u) || spu_snapshot_validate(NULL, n)) bad++;
    free(wire); free(again); free(short_wire);
    printf("%s: current SPU wire roundtrip, legacy/malformed rejection\n", bad ? "FAIL" : "PASS");
    return bad ? 1 : 0;
}
